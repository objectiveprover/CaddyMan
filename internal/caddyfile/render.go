// Package caddyfile turns CaddyMan's sites into the Caddyfile snippets
// Caddy's main Caddyfile imports, one file per site.
package caddyfile

import (
	"fmt"
	"strings"

	"caddyman/internal/config"
)

// Marker starts every file CaddyMan writes. Only files starting with it
// are ever replaced or deleted, so hand-written files in the directory are
// left alone.
const Marker = "# Generated by caddyman"

// File is a site's whole file: the marker line, then its block.
func File(c *config.Config, s config.Site) string {
	return Marker + "; edits here are overwritten (change it with CaddyMan, or edit\n" +
		"# " + config.Tilde(config.Path()) + " and run `caddyman apply`).\n" +
		Site(c, s)
}

// Site is one site's block (also used for previews, whether or not the
// site is enabled).
func Site(c *config.Config, s config.Site) string {
	var b strings.Builder
	addr := c.Address(s)
	if addr == "" {
		addr = "name." + c.DomainSuffix
	}
	if !s.HTTPS {
		addr = "http://" + addr
	}
	b.WriteString(addr + " {\n")
	line := func(f string, a ...any) { fmt.Fprintf(&b, "\t"+f+"\n", a...) }
	if s.HTTPS {
		line("tls internal")
	}
	if s.TrustedOnly {
		line("import %s", Quote(c.TrustedSnippet))
	}
	if s.RedirectRoot != "" {
		line("redir / %s", Quote(s.RedirectRoot))
	}
	switch s.Kind {
	case config.Static:
		line("root * %s", Quote(config.ExpandTilde(s.Root)))
		line("file_server")
	default:
		up := config.NormalizeUpstream(s.Upstream)
		if up == "" || s.IsAuto() { // auto: resolved before files are written
			up = "localhost:PORT"
		}
		line("reverse_proxy %s", Quote(up))
	}
	b.WriteString("}\n")
	return b.String()
}

// Quote makes a Caddyfile token: as is when it's plain, otherwise in double
// quotes with " and \ escaped.
func Quote(s string) string {
	if s != "" && !strings.ContainsAny(s, " \t\n\"\\{}#'`") {
		return s
	}
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`)
	return `"` + r.Replace(s) + `"`
}
